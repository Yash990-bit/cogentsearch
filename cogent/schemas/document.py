"""
Pydantic V2 Data Contracts for Multimodal Agentic Document Intelligence.
Defines schemas for bounding boxes, visual elements, hierarchical chunks, and complete multimodal documents.
"""

from __future__ import annotations
from enum import Enum
from datetime import datetime, timezone
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field, ConfigDict, model_validator


class VisualElementType(str, Enum):
    """Categorization of detected visual and tabular components."""
    IMAGE = "image"
    TABLE = "table"
    CHART = "chart"
    DIAGRAM = "diagram"
    INFOGRAPHIC = "infographic"
    UNKNOWN = "unknown"


class ChunkType(str, Enum):
    """Semantic type of content within a document chunk."""
    TEXT = "text"
    TABLE = "table"
    VISUAL_SUMMARY = "visual_summary"
    MIXED = "mixed"


class BoundingBox(BaseModel):
    """
    Normalized and absolute coordinate bounding box for an element on a document page.
    Follows standard document coordinate system: (x0, y0) is top-left, (x1, y1) is bottom-right.
    Guarantees strict geometric validity: 0 <= x0 < x1 and 0 <= y0 < y1 within page bounds.
    """
    model_config = ConfigDict(frozen=True)

    page_number: int = Field(..., ge=1, description="1-indexed page or slide number")
    x0: float = Field(..., description="Top-left X coordinate")
    y0: float = Field(..., description="Top-left Y coordinate")
    x1: float = Field(..., description="Bottom-right X coordinate")
    y1: float = Field(..., description="Bottom-right Y coordinate")
    page_width: Optional[float] = Field(default=None, description="Original page/slide width in points")
    page_height: Optional[float] = Field(default=None, description="Original page/slide height in points")

    @model_validator(mode="after")
    def validate_bounds(self) -> "BoundingBox":
        # Enforce positive dimensions
        if self.x1 <= self.x0:
            raise ValueError(f"Invalid BoundingBox: x1 ({self.x1}) must be strictly greater than x0 ({self.x0})")
        if self.y1 <= self.y0:
            raise ValueError(f"Invalid BoundingBox: y1 ({self.y1}) must be strictly greater than y0 ({self.y0})")

        # Non-negative coordinates (with 1pt tolerance)
        if self.x0 < -1.0 or self.y0 < -1.0:
            raise ValueError(f"Invalid BoundingBox: coordinates cannot be negative: ({self.x0}, {self.y0})")

        # Clamp against page bounds if page dimensions are given
        if self.page_width and self.x1 > self.page_width + 5.0:
            raise ValueError(f"BoundingBox x1 ({self.x1}) exceeds page width ({self.page_width})")
        if self.page_height and self.y1 > self.page_height + 5.0:
            raise ValueError(f"BoundingBox y1 ({self.y1}) exceeds page height ({self.page_height})")

        return self

    @property
    def width(self) -> float:
        return abs(self.x1 - self.x0)

    @property
    def height(self) -> float:
        return abs(self.y1 - self.y0)

    @property
    def area(self) -> float:
        return self.width * self.height

    def to_normalized(self) -> "BoundingBox":
        """Returns normalized [0, 1] bounding box if page dimensions are present."""
        if self.page_width and self.page_height and self.page_width > 0 and self.page_height > 0:
            return BoundingBox(
                page_number=self.page_number,
                x0=round(max(0.0, self.x0) / self.page_width, 4),
                y0=round(max(0.0, self.y0) / self.page_height, 4),
                x1=round(min(self.page_width, self.x1) / self.page_width, 4),
                y1=round(min(self.page_height, self.y1) / self.page_height, 4),
                page_width=self.page_width,
                page_height=self.page_height,
            )
        return self


class VisualElement(BaseModel):
    """
    An extracted image or table from a document, cropped and annotated with a Vision LLM summary.
    Preserves raw extracted text separately from generated vision descriptions.
    """
    element_id: str = Field(..., description="Unique deterministic identifier (e.g. elem_p1_0)")
    element_type: VisualElementType = Field(default=VisualElementType.IMAGE, description="Visual element category")
    page_number: int = Field(..., ge=1, description="1-indexed page number")
    bounding_box: BoundingBox = Field(..., description="Coordinates on the original page")
    image_path: str = Field(..., description="Local file path to the cropped image asset")
    description: str = Field(default="", description="Deep semantic summary generated by Vision LLM")
    extracted_text: Optional[str] = Field(
        default=None,
        description="Verbatim OCR or tabular cell text extracted directly from the source asset (separate from LLM description)",
    )
    markdown_representation: Optional[str] = Field(
        default=None, 
        description="Structured Markdown table representation if the element is tabular"
    )
    confidence: float = Field(default=1.0, ge=0.0, le=1.0, description="Detection confidence")
    continuation_of: Optional[str] = Field(default=None, description="Element ID of previous page table if multi-page")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Arbitrary engine-specific metadata")


class DocumentChunk(BaseModel):
    """
    An atomic retrieval unit representing a slice of the document with full provenance.
    Enriched with headers hierarchy and injected visual element summaries.
    Maintains raw text separately from visual injections.
    """
    chunk_id: str = Field(..., description="Unique identifier for vector indexing")
    page_number: int = Field(..., ge=1, description="1-indexed source page number")
    content: str = Field(..., description="Full searchable content including structural headers and injected vision descriptions")
    raw_text: Optional[str] = Field(default=None, description="Pure textual content before any visual injection")
    injected_visual_descriptions: List[str] = Field(
        default_factory=list,
        description="List of Vision LLM descriptions injected into this chunk",
    )
    chunk_type: ChunkType = Field(default=ChunkType.TEXT, description="Primary type of the chunk")
    headers_hierarchy: List[str] = Field(
        default_factory=list, 
        description="Path of nested headings (e.g. ['Chapter 1', 'Section 1.2'])"
    )
    bounding_boxes: List[BoundingBox] = Field(
        default_factory=list, 
        description="Bounding boxes of all visual or text blocks covered by this chunk"
    )
    visual_element_ids: List[str] = Field(
        default_factory=list, 
        description="References to VisualElement IDs embedded or described in this chunk"
    )
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Custom metadata for filtering/reranking")


class MultimodalDocument(BaseModel):
    """
    Root multimodal document model encapsulating raw structure, visual elements,
    and semantic chunks ready for downstream embedding, retrieval, and agentic workflows.
    """
    document_id: str = Field(..., description="Unique document ID (hash of binary contents)")
    filename: str = Field(..., description="Source filename")
    file_path: str = Field(..., description="Absolute path to the source file")
    file_type: str = Field(..., description="Extension or MIME type (pdf, docx, pptx)")
    total_pages: int = Field(default=1, ge=1, description="Total number of pages or slides")
    chunks: List[DocumentChunk] = Field(default_factory=list, description="Ordered chunks for vector storage")
    visual_elements: List[VisualElement] = Field(default_factory=list, description="All cropped and annotated visual assets")
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc), description="Ingestion timestamp")
    raw_metadata: Dict[str, Any] = Field(default_factory=dict, description="Document author, title, creation date, etc.")

    def get_summary_stats(self) -> Dict[str, Any]:
        """Returns quantitative metrics for ingestion reporting."""
        return {
            "document_id": self.document_id,
            "filename": self.filename,
            "file_type": self.file_type,
            "total_pages": self.total_pages,
            "total_chunks": len(self.chunks),
            "total_visual_elements": len(self.visual_elements),
            "total_tables": sum(1 for v in self.visual_elements if v.element_type == VisualElementType.TABLE),
            "total_images": sum(1 for v in self.visual_elements if v.element_type != VisualElementType.TABLE),
        }
